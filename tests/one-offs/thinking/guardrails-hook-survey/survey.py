#!/usr/bin/env python3
"""Read-only survey: which git checkouts carry git-repokit guardrails hooks,
git-repokit-common hooks, or something else.

Walks ROOT (default C:\\code) to a fixed depth, finds every directory that
holds a `.git` (dir or file), resolves its real hooks directory with git
(read-only), and classifies each hook by CONTENT markers. Never writes to any
repository; never prints hook contents (only a short content hash so variants
can be grouped).

Usage:
    python survey.py [ROOT] [--depth N] [--out FILE]
"""

import argparse
import hashlib
import os
import subprocess
import sys
from pathlib import Path

SKIP_NAMES = {"node_modules", ".venv", "venv", "__pycache__", "dist", "build",
              "site-packages", ".git"}
SKIP_SUBSTR = ("old_test_runs", "test_runs")

# Content markers. Order matters: first match wins.
PRE_COMMIT_RULES = [
    ("guardrails", ("RepoKit Cross-Environment Pre-Commit Hook",
                    "RepoKit pre-commit hook for private content protection",
                    # older (2025) python-only guardrails pre-commit
                    "RepoKit Pre-Commit Hook with Private Content Guardrails")),
    ("rk-create", ("Pre-commit hook to prevent committing private content to public branches",
                   "Generated by RepoKit using BranchContext patterns")),
    ("rkc-stub", ("repokit-common hook stub",)),
    ("rkc-full", ("repokit-common", "Updates version.py with correct version info")),
    ("rk-template", ("Pre-commit hook to prevent committing private content",)),
    # per-project copies of the repokit-common template (version.h, _version.py, ...)
    ("rkc-family", ("# Pre-commit hook that:",)),
    ("lfs", ("git lfs", "git-lfs")),
    ("husky", ('/h"', "husky")),
]
POST_CHECKOUT_RULES = [
    ("guardrails", ("RepoKit Cross-Environment Post-Checkout Hook",
                    "RepoKit post-checkout hook to update excludes and restore private files")),
    # oldest guardrails post-checkout: excludes only, no file restore
    ("guardrails-v0", ("RepoKit post-checkout hook to update branch excludes",)),
    ("rkc-stub", ("repokit-common hook stub",)),
    ("rkc-full", ("repokit-common",)),
    # non-RepoKit hooks that also restore private files on branch switch
    ("restore-other", ("Restores private-only files", "Restores private files when switching")),
    ("lfs", ("git lfs", "git-lfs")),
    ("husky", ('/h"', "husky")),
]
GENERIC_RULES = [
    ("rkc-stub", ("repokit-common hook stub",)),
    ("rkc-full", ("repokit-common",)),
    ("rkc-precursor", ("from Git-RepoKit versioning system",)),
    ("rk-other", ("RepoKit",)),
    # per-project copies of the repokit-common/Git-RepoKit versioning templates
    ("rkc-family", ("with the actual commit hash after commit",
                    "Runs basic quality checks before pushing to remote")),
    ("lfs", ("git lfs", "git-lfs")),
    ("husky", ('/h"', "husky")),
]
HOOK_RULES = {
    "pre-commit": PRE_COMMIT_RULES,
    "post-checkout": POST_CHECKOUT_RULES,
    "pre-push": GENERIC_RULES,
    "post-commit": GENERIC_RULES,
}


def git(path, *args):
    env = dict(os.environ, GIT_OPTIONAL_LOCKS="0")
    try:
        r = subprocess.run(["git", "-C", str(path), *args], capture_output=True,
                           text=True, encoding="utf-8", errors="replace",
                           timeout=20, env=env)
        return r.returncode, r.stdout.strip()
    except (OSError, subprocess.TimeoutExpired):
        return -1, ""


def find_checkouts(root, max_depth):
    root = Path(root)
    found = []

    def walk(d, depth):
        try:
            entries = list(os.scandir(d))
        except OSError:
            return
        names = {e.name for e in entries}
        if ".git" in names and depth > 0:
            found.append(Path(d))
        if depth >= max_depth:
            return
        for e in entries:
            if e.name in SKIP_NAMES or any(s in e.name for s in SKIP_SUBSTR):
                continue
            try:
                if e.is_dir(follow_symlinks=False) and not e.is_junction():
                    walk(e.path, depth + 1)
            except (OSError, AttributeError):
                try:
                    if e.is_dir(follow_symlinks=False):
                        walk(e.path, depth + 1)
                except OSError:
                    pass

    walk(root, 0)
    return found


def classify(hook_path, rules):
    if not hook_path.is_file():
        return "none", ""
    try:
        data = hook_path.read_bytes()
    except OSError:
        return "unreadable", ""
    text = data.decode("utf-8", errors="replace")
    sha = hashlib.sha256(data).hexdigest()[:8]
    for kind, markers in rules:
        if any(m in text for m in markers):
            return kind, sha
    return "other", sha


def survey_one(path):
    rec = {"path": str(path)}
    gitp = path / ".git"
    rec["gitkind"] = "file" if gitp.is_file() else "dir"
    rc, hooks = git(path, "rev-parse", "--git-path", "hooks")
    if rc != 0 or not hooks:
        reason = "rev-parse-failed"
        if gitp.is_file():
            try:
                target = gitp.read_text(encoding="utf-8", errors="replace").split("gitdir:", 1)[-1].strip()
                if target and not Path(target).exists():
                    reason = "gitdir-pointer-target-missing"
            except OSError:
                pass
        elif not (gitp / "HEAD").exists():
            reason = "git-dir-has-no-HEAD"
        rec["error"] = reason
        hooks_dir = gitp / "hooks"
    else:
        hooks_dir = Path(hooks)
        if not hooks_dir.is_absolute():
            hooks_dir = (path / hooks_dir).resolve()
    rec["hooks_dir"] = str(hooks_dir)
    _, hp = git(path, "config", "--get", "core.hooksPath")
    rec["hooksPath"] = hp or "-"
    rc, br = git(path, "symbolic-ref", "--short", "-q", "HEAD")
    rec["branch"] = br if rc == 0 and br else "(detached)"
    rc, _ = git(path, "rev-parse", "--verify", "-q", "refs/heads/private")
    rec["private_branch"] = "yes" if rc == 0 else "no"
    rec["private_repo"] = "yes" if (path / "private" / ".git").exists() else "no"
    rec["rkc_subtree"] = "yes" if (path / "scripts" / "repokit-common").is_dir() else "no"
    rec["flat_config"] = "yes" if (path / "scripts" / "repokit_config.py").is_file() else "no"
    for name, rules in HOOK_RULES.items():
        kind, sha = classify(hooks_dir / name, rules)
        rec[name] = kind + (f"@{sha}" if sha else "")
    known = set(HOOK_RULES)
    extra = []
    try:
        for e in sorted(os.listdir(hooks_dir)):
            if e in known or e.endswith(".sample") or ".backup" in e or e == "lib.sh":
                continue
            if (hooks_dir / e).is_file():
                extra.append(e)
    except OSError:
        pass
    rec["other_hooks"] = ",".join(extra) or "-"
    return rec


FIELDS = ["pre-commit", "post-checkout", "pre-push", "post-commit", "branch",
          "private_branch", "private_repo", "rkc_subtree", "flat_config",
          "gitkind", "hooksPath", "other_hooks", "hooks_dir"]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("root", nargs="?", default=r"C:\code")
    ap.add_argument("--depth", type=int, default=4)
    ap.add_argument("--out")
    a = ap.parse_args(argv)
    checkouts = find_checkouts(a.root, a.depth)
    lines = [f"# guardrails hook survey  root={a.root}  depth={a.depth}  "
             f"skip={sorted(SKIP_NAMES)} + names containing {SKIP_SUBSTR}",
             f"# checkouts: {len(checkouts)}",
             "# kinds: guardrails = repokit setup-guardrails (any version); guardrails-v0 = oldest "
             "excludes-only post-checkout; rk-create = repokit create's pre-commit; rk-template = "
             "repokit/hooks/pre-commit-template; rkc-stub = repokit-common install-hooks.sh stub; "
             "rkc-full = full copy naming repokit-common; rkc-family = per-project copy of the "
             "repokit-common/Git-RepoKit versioning templates; rkc-precursor = 'Git-RepoKit versioning "
             "system' pre-push; restore-other = non-RepoKit post-checkout that restores private files; "
             "lfs/husky = third-party; @xxxxxxxx = first 8 hex of the hook's SHA-256",
             "# path | " + " | ".join(FIELDS)]
    for p in checkouts:
        r = survey_one(p)
        row = [r["path"]] + [f"{k}={r.get(k, '?')}" for k in FIELDS]
        if "error" in r:
            row.append("error=" + r["error"])
        lines.append(" | ".join(row))
    out = "\n".join(lines) + "\n"
    if a.out:
        Path(a.out).parent.mkdir(parents=True, exist_ok=True)
        Path(a.out).write_text(out, encoding="utf-8")
        print(f"wrote {len(checkouts)} rows to {a.out}")
    else:
        sys.stdout.write(out)


if __name__ == "__main__":
    main()
